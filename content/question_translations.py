def apply_translations(exams):
    for exam in exams:
        for problem in exam['problems']:
            statement, prompts = TRANSLATIONS[problem['id']]
            assert len(prompts) == len(problem['parts']), problem['id']
            problem['title']['zh'] = TITLES[problem['id']]
            problem['statement']['zh'] = statement
            for part, prompt in zip(problem['parts'], prompts):
                part['prompt']['zh'] = prompt
